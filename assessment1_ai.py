"""Test on one image"""

def predict_single_image(image_path, model, feature_type="LBP"):
    img = cv2.imread(image_path, cv2.IMREAD_GRAYSCALE)
    if img is None:
        print("Error: image not found at path", image_path)
        return

    faces = face_cascade.detectMultiScale(img, scaleFactor=1.1, minNeighbors=5, minSize=(30,30))
    if len(faces) == 0:
        print("No face detected in the image")
        return

    for (x,y,w,h) in faces:
        face_region = img[y:y+h, x:x+w]

        # Use version 3
        if feature_type == "LBP":
            features = extract_lbp_features_v3([face_region], radius=2)
        elif feature_type == "HOG":
            features = extract_hog_features_v3([face_region])
        else:
            print("Unknown feature type:", feature_type)
            return

        # Prediction
        pred = model.predict(features)[0]
        print(f"Predicted Emotion: {pred}")

        # Visualization
        img_color = cv2.imread(image_path)
        img_color = cv2.cvtColor(img_color, cv2.COLOR_BGR2RGB)
        cv2.rectangle(img_color, (x,y), (x+w,y+h), (255,0,0), 2)
        cv2.putText(img_color, pred, (x,y-10), cv2.FONT_HERSHEY_SIMPLEX, 0.9, (255,0,0), 2)

        plt.figure(figsize=(6,6))
        plt.imshow(img_color)
        plt.axis('off')
        plt.title(f"Predicted Emotion: {pred}")
        plt.show()

