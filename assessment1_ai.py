"""Write functions to load and process data"""

# Haar Cascade face detection
face_cascade = cv2.CascadeClassifier('/content/drive/MyDrive/haarcascade_frontalface_default.xml')

def load_and_detect_faces(folder_path):
    images, labels = [], []
    for label in os.listdir(folder_path):
        label_path = os.path.join(folder_path, label)
        if os.path.isdir(label_path):
            for img_file in os.listdir(label_path):
                img_path = os.path.join(label_path, img_file)
                img = cv2.imread(img_path, cv2.IMREAD_GRAYSCALE)
                if img is not None:
                    faces = face_cascade.detectMultiScale(img, scaleFactor=1.1, minNeighbors=5, minSize=(30,30))
                    for (x,y,w,h) in faces:
                        face_region = img[y:y+h, x:x+w]
                        images.append(face_region)
                        labels.append(label)
    return images, labels

"""Features (LBP and HOG)"""

# version 0
def extract_lbp_features(images, radius=1):
    n_points = 8 * radius
    features = []
    for img in images:
        img = cv2.resize(img, (64,64))
        lbp = local_binary_pattern(img, n_points, radius, method="uniform")
        hist, _ = np.histogram(lbp.ravel(), bins=np.arange(0, n_points+3), range=(0, n_points+2))
        hist = hist.astype("float")
        hist /= (hist.sum() + 1e-6)
        features.append(hist)
    return np.array(features)

def extract_hog_features(images):
    features = []
    for img in images:
        img = cv2.resize(img, (64,64))
        hog_feat = hog(img, orientations=8, pixels_per_cell=(8,8),
                       cells_per_block=(2,2), block_norm='L2-Hys')
        features.append(hog_feat)
    return np.array(features)

